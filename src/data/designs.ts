export const DESIGNS_OBJ = DESIGNS.reduce(
  (acc, product) => {
    const { id, ...rest } = product;
    return { ...acc, [id]: rest };
  },
  {} as Record<string, Omit<(typeof DESIGNS)[number], "id">>
);

export const getColorVariantIds = (designId: string) => {
  const family = DESIGNS_OBJ[designId]?.family;
  return family ? DESIGNS.filter(d => d.family === family).map(d => d.id) : [];
};
